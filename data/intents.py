def build_dataset():
    """Возвращает (X_text, y) для обучения классификатора."""
    x_text, y = [], []
    for intent, data in BOT_CONFIG["intents"].items():
        for example in data["examples"]:
            x_text.append(example)
            y.append(intent)
    return x_text, y


def intent_vocabulary() -> set:
    """Словарь слов для исправления опечаток."""
    words = set()
    for data in BOT_CONFIG["intents"].values():
        for example in data["examples"]:
            words.update(example.lower().split())
    return {w for w in words if len(w) > 3}
